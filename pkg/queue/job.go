package queue

import (
	"crypto/rand"
	"encoding/hex"
	"errors"
	"time"
)

var (
	ErrJobNotFound        = errors.New("job not found")
	ErrJobAlreadyExists   = errors.New("job with idempotency key already processed or active")
	ErrQueueEmpty         = errors.New("queue is empty")
	ErrLeaseExpired       = errors.New("job visibility lease expired")
	ErrMaxRetriesExceeded = errors.New("maximum retries exhausted; routed to DLQ")
)

// State represents the lifecycle status of a job.
type State string

const (
	StatePending      State = "pending"
	StateProcessing   State = "processing"
	StateCompleted    State = "completed"
	StateFailed       State = "failed"
	StateDelayed      State = "delayed"
	StateDeadLettered State = "dead_lettered"
)

// Job represents a unit of asynchronous work.
type Job struct {
	ID                 string            `json:"id"`
	Queue              string            `json:"queue"`
	Payload            []byte            `json:"payload"`
	IdempotencyKey     string            `json:"idempotency_key,omitempty"`
	State              State             `json:"state"`
	MaxRetries         int               `json:"max_retries"`
	RetryCount         int               `json:"retry_count"`
	VisibilityTimeout  time.Duration     `json:"visibility_timeout"`
	VisibilityDeadline time.Time         `json:"visibility_deadline"`
	NextRunAt          time.Time         `json:"next_run_at"`
	CreatedAt          time.Time         `json:"created_at"`
	UpdatedAt          time.Time         `json:"updated_at"`
	CompletedAt        *time.Time        `json:"completed_at,omitempty"`
	LastError          string            `json:"last_error,omitempty"`
	WorkerID           string            `json:"worker_id,omitempty"`
	Metadata           map[string]string `json:"metadata,omitempty"`
}

// NewJob constructs a job with sane defaults and an autogenerated UUID.
func NewJob(queue string, payload []byte) *Job {
	now := time.Now().UTC()
	return &Job{
		ID:                generateID(),
		Queue:             queue,
		Payload:           payload,
		State:             StatePending,
		MaxRetries:        3,
		VisibilityTimeout: 30 * time.Second,
		NextRunAt:         now,
		CreatedAt:         now,
		UpdatedAt:         now,
		Metadata:          make(map[string]string),
	}
}

func generateID() string {
	b := make([]byte, 12)
	_, _ = rand.Read(b)
	return hex.EncodeToString(b)
}
